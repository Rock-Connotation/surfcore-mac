import assert from 'node:assert/strict';
import { parseDouyinSelf, parseDouyinFeed, publicDouyinAccount } from '../lib/douyin-data.mjs';

const SELF_PATH = '/aweme/v1/web/user/profile/self/';
const FEED_PATH = '/aweme/v1/web/tab/feed/';
const selfParse = (payload) => parseDouyinSelf(payload, { sourcePath: SELF_PATH });
const feedParse = (payload, options = {}) => parseDouyinFeed(payload, { sourcePath: FEED_PATH, ...options });

const failure = (result, code) => {
  assert.equal(result.ok, false);
  assert.equal(result.code, code);
  assert.ok(result.error && result.hint);
};
const self = selfParse({ status_code: 0, user: { uid: '123456789', sec_uid: 'sec', nickname: '名字', phone: 'secret-phone' }, cookie: 'secret-cookie' });
assert.equal(self.ok, true);
assert.equal(self.identity.uid, '123456789');
assert.equal(self.identity.accountKey.length, 64);
assert.deepEqual(publicDouyinAccount(self.identity), { configured: true, nickname: '名字', uidSuffix: '6789' });
assert.deepEqual(publicDouyinAccount(null), { configured: false });
assert.equal(publicDouyinAccount({ uid: '123', nickname: 'n' }).uidSuffix, null);
failure(selfParse({ data: { is_login: true, user_id: '123456', nickname: '名字' } }), 'DOUYIN_SELF_UNAUTHENTICATED');
failure(selfParse({ data: { is_login: false, user_id: '123456', nickname: '游客' } }), 'DOUYIN_SELF_UNAUTHENTICATED');
failure(selfParse({ user: { uid: '123456', nickname: '作者' } }), 'DOUYIN_SELF_UNAUTHENTICATED');
failure(selfParse({ status_code: 0, user: { uid: '0', nickname: '游客' } }), 'DOUYIN_SELF_INVALID');
failure(selfParse({ status_code: 0, user: { uid: '123456', nickname: '游客', is_guest: true } }), 'DOUYIN_SELF_UNAUTHENTICATED');
failure(selfParse({ status_code: 0, user: { uid: '123456', nickname: '游客', is_login: false } }), 'DOUYIN_SELF_UNAUTHENTICATED');
failure(selfParse({ status_code: 0, user: { uid: '123456', nickname: '' } }), 'DOUYIN_SELF_INVALID');
const makeItem = (id) => ({ aweme_id: String(id), desc: 'x'.repeat(2100), author: { uid: '987654321', nickname: '作者', signature: 'secret-bio' }, video: { duration: 3210, play_addr: { url_list: ['secret-url'] } }, create_time: 1700000000, cookie: 'secret-cookie' });
const feed = feedParse({ status_code: 0, aweme_list: Array.from({ length: 8 }, (_, i) => makeItem(i + 1)), headers: 'secret-headers' }, { limit: 100 });
assert.equal(feed.ok, true);
assert.equal(feed.source, 'homepage-recommendation');
assert.equal(feed.items.length, 5);
assert.equal(feed.items[0].url, 'https://www.douyin.com/video/1');
assert.equal(feed.items[0].description.length, 2000);
assert.equal(feed.items[0].durationMs, 3210);
const invalidDuration = makeItem(9);
invalidDuration.video.duration = -1;
assert.equal('durationMs' in feedParse({ status_code: 0, aweme_list: [invalidDuration] }).items[0], false);
assert.deepEqual(feed.items[0].author, { nickname: '作者', uidSuffix: '4321' });
assert.doesNotMatch(JSON.stringify(feed), /secret-|987654321|accountKey/);
assert.equal(feedParse({ status_code: 0, aweme_list: [makeItem(1), makeItem(2)] }, { limit: 1 }).items.length, 1);
for (const input of [{ status_code: 0, post_list: [makeItem(1)] }, { status_code: 0, related_videos: [makeItem(1)] }, { status_code: 1, aweme_list: [makeItem(1)] }, null]) failure(feedParse(input), 'DOUYIN_FEED_INVALID');
failure(feedParse({ status_code: 0, aweme_list: [] }), 'DOUYIN_FEED_EMPTY');
failure(feedParse({ status_code: 0, aweme_list: [makeItem('0')] }), 'DOUYIN_FEED_ITEM_INVALID');
failure(feedParse({ status_code: 0, aweme_list: [makeItem('1/evil')] }), 'DOUYIN_FEED_ITEM_INVALID');
failure(feedParse({ status_code: 0, aweme_list: [makeItem(1)] }, { limit: 0 }), 'DOUYIN_FEED_LIMIT');
failure(parseDouyinSelf({ status_code: 0, user: { uid: '123456', nickname: '名字' } }), 'DOUYIN_SELF_SOURCE');
failure(parseDouyinSelf({ status_code: 0, user: { uid: '123456', nickname: '名字' } }, { sourcePath: '/aweme/v1/web/user/profile/other/' }), 'DOUYIN_SELF_SOURCE');
failure(parseDouyinFeed({ status_code: 0, aweme_list: [makeItem(1)] }), 'DOUYIN_FEED_SOURCE');
for (const sourcePath of ['/aweme/v1/web/aweme/post/', '/aweme/v1/web/related/', '']) failure(feedParse({ status_code: 0, aweme_list: [makeItem(1)] }, { sourcePath }), 'DOUYIN_FEED_SOURCE');
failure(parseDouyinFeed({ status_code: 0, aweme_list: [makeItem(1)] }, null), 'DOUYIN_FEED_SOURCE');
console.log('douyin data projection: ok');
