import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { voiceSendBudget as budget } from '../src/voice-send-budget.js';
import { reserveVolcBudget, effectiveVolcMonthLimit } from '../src/voice-volc-budget.js';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'surfcore-quota-'));
const state = path.join(root, 'state');
const at = new Date(2026, 10, 10, 12).getTime();
const file = path.join(state, 'voice-send-budget.json');
try {
  assert.throws(() => budget(state,'check',at), {code:'VOICE_SEND_BASELINE_REQUIRED'});
  assert.equal(JSON.parse(fs.readFileSync(file)).count,500);
  fs.writeFileSync(file,JSON.stringify({version:2,day:'2026-11-10',count:0,lastAt:0,pending:null,reconciliations:[]}),{mode:0o600});
  const id = budget(state, {type:'reserve',key:'private:123'}, at);
  assert.throws(() => budget(state, {type:'reserve',key:'group:456'}, at), {code:'VOICE_SEND_BUDGET_BUSY'});
  budget(state, {id, result:'rejected'}, at);
  assert.equal(JSON.parse(fs.readFileSync(file)).count, 0);
  for (let i=0; i<500; i++) { const id=budget(state, {type:'reserve',key:'private:123'}, at+i); budget(state, {id, result:'sent'}, at+i); }
  assert.equal(JSON.parse(fs.readFileSync(file)).count, 500);
  assert.throws(() => budget(state, {type:'reserve',key:'private:123'}, at+501), e => e.code === 'VOICE_DAILY_LIMIT' && !!e.hint);
  const child = spawnSync(process.execPath, ['--input-type=module', '-e', `import {voiceSendBudget} from ${JSON.stringify(new URL('../src/voice-send-budget.js',import.meta.url).href)}; try { voiceSendBudget(process.argv[1], {type:'reserve',key:'private:123'}, Number(process.argv[2])); process.exit(1); } catch(e) { if(e.code !== 'VOICE_DAILY_LIMIT') process.exit(2); }`, state, String(at+501)]);
  assert.equal(child.status,0);
  const next = new Date(2026,10,11,0,0,0).getTime();
  const nextId=budget(state,{type:'reserve',key:'private:123'},next); budget(state,{id:nextId,result:'sent'},next);
  assert.equal(JSON.parse(fs.readFileSync(file)).count,1);
  const end = new Date(2026,10,11,23,59,59).getTime();
  const crossing=budget(state,{type:'reserve',key:'private:123'},end); budget(state,{id:crossing,result:'sent'},end+2000);
  assert.equal(JSON.parse(fs.readFileSync(file)).count,1);
  const uncertain=budget(state,{type:'reserve',key:'private:123'},end+2001);
  budget(state,{id:uncertain,result:'uncertain'},end+2002);
  assert.throws(() => budget(state,'check',end+2002),{code:'VOICE_SEND_UNCERTAIN'});
  budget(state,{type:'reconcile',id:uncertain,result:'rejected',evidence:'confirmed gateway rejection'},end+2002);
  assert.equal(JSON.parse(fs.readFileSync(file)).reconciliations.length,1);
  const raceDir = path.join(root,'race');
  fs.mkdirSync(raceDir); fs.writeFileSync(path.join(raceDir,'voice-send-budget.json'),JSON.stringify({version:2,day:'2026-11-10',count:0,lastAt:0,pending:null,reconciliations:[]}),{mode:0o600});
  const worker = `import {voiceSendBudget as b} from ${JSON.stringify(new URL('../src/voice-send-budget.js',import.meta.url).href)}; try { b(process.argv[1],{type:'reserve',key:'private:123'},Number(process.argv[2])); console.log('reserved'); } catch(e) { console.log(e.code); }`;
  const runWorker = () => new Promise((resolve,reject) => { let out=''; const p=spawn(process.execPath,['--input-type=module','-e',worker,raceDir,String(at)]); p.stdout.on('data',x=>out+=x); p.on('error',reject); p.on('close',code=>code===0?resolve(out.trim()):reject(new Error(`worker ${code}`))); });
  const raced=await Promise.all([runWorker(),runWorker()]);
  assert.equal(raced.filter(x=>x==='reserved').length,1);
  assert.ok(raced.some(x=>['VOICE_SEND_UNCERTAIN','VOICE_SEND_BUDGET_BUSY'].includes(x)));
  assert.throws(()=>budget(raceDir,{type:'reserve',key:'private:123'},at+1),{code:'VOICE_SEND_UNCERTAIN'});
  const lockDir=path.join(root,'stale'); fs.mkdirSync(lockDir); fs.writeFileSync(path.join(lockDir,'voice-send-budget.json'),JSON.stringify({version:2,day:'2026-11-10',count:0,lastAt:0,pending:null,reconciliations:[]}),{mode:0o600});
  const lockWorker=`import fs from 'node:fs'; const p=process.argv[1]; const t=p+'.candidate'; fs.writeFileSync(t,JSON.stringify({pid:process.pid,owner:'11111111-1111-4111-8111-111111111111'}),{mode:0o600}); fs.linkSync(t,p); console.log('locked'); setInterval(()=>{},1000);`;
  const holder=spawn(process.execPath,['--input-type=module','-e',lockWorker,path.join(lockDir,'voice-send-budget.lock')]);
  await new Promise((resolve,reject)=>{holder.stdout.once('data',resolve);holder.once('error',reject)});
  assert.throws(()=>budget(lockDir,'check',at),{code:'VOICE_SEND_BUDGET_BUSY'});
  const stopped=new Promise(resolve=>holder.once('close',resolve)); holder.kill('SIGKILL'); await stopped;
  const recovered=budget(lockDir,{type:'reserve',key:'private:123'},at); budget(lockDir,{id:recovered,result:'rejected'},at);
  const crossingDir=path.join(root,'crossing'); fs.mkdirSync(crossingDir); fs.writeFileSync(path.join(crossingDir,'voice-send-budget.json'),JSON.stringify({version:2,day:'2026-11-11',count:3,lastAt:0,pending:null,reconciliations:[]}),{mode:0o600});
  const late=budget(crossingDir,{type:'reserve',key:'private:123'},end); budget(crossingDir,{id:late,result:'uncertain'},end+100);
  budget(crossingDir,{type:'reconcile',id:late,result:'sent',acceptedAt:end+500,evidence:'gateway accepted receipt'},end+2000);
  assert.equal(budget(crossingDir,'inspect',end+2000).count,4);
  const afterMidnight=budget(crossingDir,{type:'reserve',key:'group:456'},end+2001); budget(crossingDir,{id:afterMidnight,result:'sent'},end+2001);
  assert.equal(budget(crossingDir,'inspect',end+2002).count,1);
  const migrateDir=path.join(root,'migration'); budget(migrateDir,'initialize',at); budget(migrateDir,'initialize',at+1);
  assert.equal(budget(migrateDir,'inspect',at+1).count,500); assert.doesNotThrow(()=>budget(migrateDir,'check',next));
  const seed=path.join(root,'seed');
  budget(seed,{type:'initialize',count:2,evidence:'verified gateway send history'},at);
  budget(seed,{type:'initialize',count:0,evidence:'must not overwrite existing'},at+1);
  assert.equal(budget(seed,'inspect',at+1).count,2);
  assert.equal(budget(seed,'inspect',at+1).reconciliations[0].type,'opening-balance');
  assert.equal(effectiveVolcMonthLimit(900000),900000);
  const configFile=path.join(root,'config.json'); fs.writeFileSync(configFile,JSON.stringify({socialV2:{voice:{maxPerMinute:30,maxPerHour:100}}}));
  const monthState=path.join(root,'state','volc-voice-budget.json');
  const stamp=Date.UTC(2026,10,30,23,59);
  fs.writeFileSync(monthState, JSON.stringify({version:1,month:'2026-11',chars:899999,lastAt:stamp-100,events:[]}),{mode:0o600});
  reserveVolcBudget({configFile,text:'a',now:stamp,monthlyQuota:900000,maxPerMinute:30,maxPerHour:100});
  assert.throws(()=>reserveVolcBudget({configFile,text:'a',now:stamp+1,monthlyQuota:900000,maxPerMinute:30,maxPerHour:100}),{code:'VOICE_VOLC_BUDGET_EXHAUSTED'});
  reserveVolcBudget({configFile,text:'a',now:Date.UTC(2026,11,1),monthlyQuota:900000,maxPerMinute:30,maxPerHour:100});
  assert.equal(JSON.parse(fs.readFileSync(monthState)).chars,1);
  fs.writeFileSync(monthState, JSON.stringify({version:1,month:'2026-12',chars:0,lastAt:Date.UTC(2026,11,1),events:[]}),{mode:0o600});
  for(let i=0;i<30;i++) reserveVolcBudget({configFile,text:'a',now:Date.UTC(2026,11,1)+i,maxPerMinute:30,maxPerHour:100});
  assert.throws(()=>reserveVolcBudget({configFile,text:'a',now:Date.UTC(2026,11,1)+31,maxPerMinute:30,maxPerHour:100}),e=>e.code==='VOICE_VOLC_BUDGET_EXHAUSTED'&&e.message.includes('每分钟')&&!!e.hint);
  const billTime=Date.UTC(2026,11,2);
  assert.throws(()=>reserveVolcBudget({configFile,text:'charged',now:billTime,startRequest(){ throw new Error('provider failure'); }}));
  assert.equal(JSON.parse(fs.readFileSync(monthState)).chars,37);
  assert.equal(effectiveVolcMonthLimit(100000),100000);


  console.log('quota regression passed: 500, restart, failures, midnight and UTC month');
} finally { fs.rmSync(root,{recursive:true,force:true}); }
