import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { openLegacyRegistry } from '../src/core/memory-v2-legacy-registry.js';
import { planLegacyMigration } from '../src/core/memory-v2-migration-plan.js';

const root = path.resolve('_backups/memory-v2-legacy-registry', `synthetic-${Date.now()}-${process.pid}`);
fs.mkdirSync(root, { recursive: true });
const filePath = path.join(root, 'registry.sqlite');
assert.equal(openLegacyRegistry(null).code, 'LEGACY_REGISTRY_ARGUMENT_INVALID');
const registry = openLegacyRegistry({ filePath, create: true });
assert.equal(registry.ok, true);
const record = (logicalStreamKey, segmentIdentity) => registry.register({ logicalStreamKey, segmentIdentity });
const initial = record('inbox-segment-1', 'verified-segment-a');
assert.equal(initial.ok, true);
assert.equal(record('inbox-segment-1', 'verified-segment-a').legacyStreamId, initial.legacyStreamId);
assert.equal(record('inbox-segment-1', 'verified-segment-b').code, 'LEGACY_REGISTRY_CONFLICT');
assert.equal(record('another-key', 'verified-segment-a').code, 'LEGACY_REGISTRY_CONFLICT');
assert.equal(record('missing-evidence', '').code, 'LEGACY_REGISTRY_ARGUMENT_INVALID');
assert.equal(record('missing-evidence', null).code, 'LEGACY_REGISTRY_ARGUMENT_INVALID');
assert.equal(registry.register(null).code, 'LEGACY_REGISTRY_ARGUMENT_INVALID');
const rotated = record('inbox-segment-2', 'verified-segment-b');
assert.equal(rotated.ok, true);
assert.notEqual(rotated.legacyStreamId, initial.legacyStreamId);
const reopened = openLegacyRegistry({ filePath });
assert.equal(reopened.ok, true);
assert.deepEqual(reopened.read().streamRegistry, { 'inbox-segment-1': initial.legacyStreamId, 'inbox-segment-2': rotated.legacyStreamId });
const sourceFile = path.join(root, 'synthetic-inbox.jsonl');
fs.writeFileSync(sourceFile, JSON.stringify({ id: 'one', text: 'synthetic' }) + '\n');
const preview = planLegacyMigration({ characterId: 'alpha', capturedAt: '2026-11-09T12:00:00.000Z', sources: [{ kind: 'memory-inbox', logicalStreamKey: 'inbox-segment-1', filePath: sourceFile }], streamRegistry: reopened.read().streamRegistry });
assert.equal(preview.manifest.importReady, false);
assert.equal(preview.manifest.sources[0].legacyStreamId, initial.legacyStreamId);
assert.equal(preview.quarantine[0].authorization, 'not-issued');
assert.ok(preview.quarantine[0].reasons.includes('MIGRATION_AUTHORITY_UNKNOWN'));
fs.appendFileSync(sourceFile, JSON.stringify({ id: 'two', text: 'synthetic append' }) + '\n');
const copied = path.join(root, 'synthetic-renamed.jsonl');
fs.copyFileSync(sourceFile, copied);
const appended = planLegacyMigration({ characterId: 'alpha', capturedAt: '2026-11-09T12:00:00.000Z', sources: [{ kind: 'memory-inbox', logicalStreamKey: 'inbox-segment-1', filePath: copied }], streamRegistry: reopened.read().streamRegistry });
assert.equal(appended.manifest.sources[0].legacyStreamId, initial.legacyStreamId);
assert.equal(appended.quarantine.length, 2);
const locker = new DatabaseSync(filePath);
locker.exec('BEGIN IMMEDIATE');
const blocked = record('locked', 'verified-locked');
assert.equal(blocked.ok, false);
assert.ok(blocked.code && blocked.error && blocked.hint);
locker.exec('ROLLBACK'); locker.close();
assert.equal(reopened.read().streamRegistry.locked, undefined);
const originalExec = DatabaseSync.prototype.exec;
try {
  DatabaseSync.prototype.exec = function(sql) {
    if (sql === 'COMMIT') throw new Error('synthetic failed commit');
    return originalExec.call(this, sql);
  };
  const failed = record('failed', 'verified-failed');
  assert.equal(failed.code, 'LEGACY_REGISTRY_COMMIT_UNKNOWN');
} finally { DatabaseSync.prototype.exec = originalExec; }
assert.equal(reopened.read().streamRegistry.failed, undefined);
assert.equal(reopened.read().streamRegistry['inbox-segment-1'], initial.legacyStreamId);
try {
  DatabaseSync.prototype.exec = function(sql) {
    if (sql === 'COMMIT') { originalExec.call(this, sql); throw new Error('synthetic lost acknowledgement'); }
    return originalExec.call(this, sql);
  };
  const unknown = record('uncertain', 'verified-uncertain');
  assert.equal(unknown.code, 'LEGACY_REGISTRY_COMMIT_UNKNOWN');
  assert.equal(unknown.commitState, 'unknown');
} finally { DatabaseSync.prototype.exec = originalExec; }
const afterUnknown = openLegacyRegistry({ filePath });
const uncertainId = afterUnknown.read().streamRegistry.uncertain;
assert.ok(uncertainId);
assert.equal(afterUnknown.register({ logicalStreamKey: 'uncertain', segmentIdentity: 'verified-uncertain' }).legacyStreamId, uncertainId);
const corrupt = path.join(root, 'corrupt.sqlite');
const corruptBytes = Buffer.from('not a database, preserve these bytes');
fs.writeFileSync(corrupt, corruptBytes);
const invalid = openLegacyRegistry({ filePath: corrupt });
assert.equal(invalid.ok, false);
assert.ok(invalid.code && invalid.error && invalid.hint);
assert.deepEqual(fs.readFileSync(corrupt), corruptBytes);
const changed = path.join(root, 'changed.sqlite');
fs.copyFileSync(filePath, changed);
const tamper = new DatabaseSync(changed);
tamper.prepare('UPDATE segments SET identity=? WHERE logical=?').run('verified-altered', 'inbox-segment-1');
tamper.close();
const changedBytes = fs.readFileSync(changed);
assert.equal(openLegacyRegistry({ filePath: changed }).code, 'LEGACY_REGISTRY_CORRUPT');
assert.deepEqual(fs.readFileSync(changed), changedBytes);
assert.equal(openLegacyRegistry({ filePath, create: true }).ok, false);
assert.equal(reopened.read().streamRegistry['inbox-segment-1'], initial.legacyStreamId);
console.log('legacy registry isolated fixtures: PASS');
