import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { readMemoryRouting, writeMemoryRouting, deriveMemoryProviderRouteId } from '../src/core/memory-v2-routing.js';

const parent = path.resolve('_backups/memory-v2-routing');
fs.mkdirSync(parent, { recursive: true });
const stateDir = fs.mkdtempSync(path.join(parent, 'routing-'));
const routeFile = path.join(stateDir, 'memory-v2', 'routing.json');
const controlFile = path.join(stateDir, 'memory-control.sqlite');
const failure = (value, code) => { assert.equal(value.ok, false); assert.equal(value.code, code); assert.ok(value.error); assert.ok(value.hint); };
assert.equal(readMemoryRouting({ stateDir }).backend, 'v1');
fs.writeFileSync(controlFile, 'fixture existence only; not a SQLite capability claim');
failure(readMemoryRouting({ stateDir }), 'MEMORY_ROUTING_INVALID');
const status = { ok: true, activeBackend: 'v1', revision: 1, storeGeneration: 'generation-one' };
assert.equal(writeMemoryRouting({ stateDir, status }).ok, true);
assert.equal(readMemoryRouting({ stateDir }).backend, 'v1');
assert.equal(writeMemoryRouting({ stateDir, status }).unchanged, true);
assert.equal(writeMemoryRouting({ stateDir, status: { ...status, activeBackend: 'v2', revision: 2 } }).ok, true);
assert.equal(readMemoryRouting({ stateDir }).backend, 'v2');
failure(writeMemoryRouting({ stateDir, status }), 'MEMORY_ROUTING_ROLLBACK');
failure(writeMemoryRouting({ stateDir, status: { ...status, revision: 3 } }), 'MEMORY_ROUTING_ROLLBACK');
assert.equal(readMemoryRouting({ stateDir }).backend, 'v2');
const absentControlRoot = fs.mkdtempSync(path.join(parent, 'missing-control-'));
const absentRouteDir = path.join(absentControlRoot, 'memory-v2');
fs.mkdirSync(absentRouteDir, { mode: 0o700 });
fs.copyFileSync(routeFile, path.join(absentRouteDir, 'routing.json'));
fs.chmodSync(path.join(absentRouteDir, 'routing.json'), 0o600);
failure(readMemoryRouting({ stateDir: absentControlRoot }), 'MEMORY_CONTROL_UNAVAILABLE');
assert.equal(writeMemoryRouting({ stateDir, status: { ...status, activeBackend: 'v2', revision: 3, minCompatibleReader: 2 } }).ok, true);
failure(readMemoryRouting({ stateDir }), 'MEMORY_READER_UNSUPPORTED');
fs.copyFileSync(routeFile, path.join(stateDir, 'before-corruption.json'));
fs.writeFileSync(routeFile, '{broken', { mode: 0o600 });
failure(readMemoryRouting({ stateDir }), 'MEMORY_ROUTING_INVALID');
failure(writeMemoryRouting({ stateDir, status: { ...status, revision: 4 } }), 'MEMORY_ROUTING_WRITE_FAILED');
assert.equal(fs.readFileSync(routeFile, 'utf8'), '{broken');
const linkedRoot = fs.mkdtempSync(path.join(parent, 'linked-'));
fs.symlinkSync(absentRouteDir, path.join(linkedRoot, 'memory-v2'), 'dir');
failure(readMemoryRouting({ stateDir: linkedRoot }), 'MEMORY_ROUTING_INVALID');
failure(writeMemoryRouting({ stateDir: linkedRoot, status }), 'MEMORY_ROUTING_INVALID');
const invalidInput = deriveMemoryProviderRouteId({ provider: '', model: 'm' });
failure(invalidInput, 'MEMORY_PROVIDER_ROUTE_REQUIRED');
for (const provider of [' a', 'a\n', undefined]) failure(deriveMemoryProviderRouteId({ provider, model: 'm' }), 'MEMORY_PROVIDER_ROUTE_REQUIRED');
const exact = deriveMemoryProviderRouteId({ provider: 'a', model: 'vendor/model-中文' });
assert.equal(exact.ok, true);
assert.match(exact.providerRouteId, /^dsh-route:[a-f0-9]{64}$/);
assert.equal(deriveMemoryProviderRouteId({ model: 'vendor/model-中文', provider: 'a' }).providerRouteId, exact.providerRouteId);
assert.notEqual(deriveMemoryProviderRouteId({ provider: 'a/b', model: 'c' }).providerRouteId, deriveMemoryProviderRouteId({ provider: 'a', model: 'b/c' }).providerRouteId);
assert.notEqual(deriveMemoryProviderRouteId({ provider: 'A', model: 'vendor/model-中文' }).providerRouteId, exact.providerRouteId);
console.log('PASS persistent routing: legacy only on fresh absence, control loss/corruption/downgrade fail closed, symlink denied; exact provider/model binding is unambiguous');
